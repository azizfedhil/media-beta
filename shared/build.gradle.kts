// ---- p2p_core: the Rust P2P engine (p2p-core/) -------------------------------------------------------------------
// Built as a shared library for this OS, and bound to Kotlin with UniFFI in library mode: the same steps the iOS build
// uses for the Swift bindings. Both need Rust (cargo) on the PATH.

val p2pCrate = rootProject.file("p2p-core")
val p2pOs = System.getProperty("os.name").orEmpty().lowercase()
val p2pLibFile = when {
    "win" in p2pOs -> "p2p_core.dll"
    "mac" in p2pOs || "darwin" in p2pOs -> "libp2p_core.dylib"
    else -> "libp2p_core.so"
}
val p2pFolder = when {
    "win" in p2pOs -> "windows-x64"
    "linux" in p2pOs -> "linux-x64"
    else -> "other"
}
val p2pBuiltLib = File(p2pCrate, "target/release/$p2pLibFile")
val p2pPackagedLib = rootProject.file("desktopApp/packaging/resources/$p2pFolder/$p2pLibFile")
val p2pBindings = layout.buildDirectory.dir("generated/uniffi/kotlin")

val buildP2pCore by tasks.registering(Exec::class) {
    group = "p2p"
    description = "Builds the p2p_core engine as a shared library for this OS and copies it to the packaging folder."
    workingDir = p2pCrate
    // cdylib for this build only: the crate types in Cargo.toml stay as they are, so the iOS xcframework build is unchanged.
    commandLine("cargo", "rustc", "--release", "--lib", "--crate-type", "cdylib")
    // The p2p-core release profile strips symbols (strip = true, for the iOS size). UniFFI reads its metadata from the
    // symbol table, so a stripped library gives no bindings on Linux (Windows keeps its symbols). Keep them for this build.
    environment("CARGO_PROFILE_RELEASE_STRIP", "none")
    inputs.dir(File(p2pCrate, "src"))
    inputs.file(File(p2pCrate, "Cargo.toml"))
    outputs.file(p2pBuiltLib)
    doLast {
        p2pPackagedLib.parentFile.mkdirs()
        p2pBuiltLib.copyTo(p2pPackagedLib, overwrite = true)
    }
}

// UniFFI's output, kept so a failed check can report what the generator said (CI runs don't show it otherwise).
val bindgenOutput = ByteArrayOutputStream()

// The library as UniFFI reads it. Linux builds libp2p_core.so, and UniFFI names the Kotlin module after the file, so the
// copy drops the "lib" prefix: the module is p2p_core on every OS, which is the package the desktop code imports. The app
// itself still loads the real library; Windows' name has no prefix, so its copy keeps the same name.
val bindgenLib = layout.buildDirectory.file("p2p-bindgen/${p2pLibFile.removePrefix("lib")}").get().asFile

val generateP2pBindings by tasks.registering(Exec::class) {
    group = "p2p"
    description = "Generates the Kotlin bindings of p2p_core from the built library (UniFFI, library mode)."
    dependsOn(buildP2pCore)
    workingDir = p2pCrate
    standardOutput = bindgenOutput
    errorOutput = bindgenOutput
    commandLine(
        "cargo", "run", "--release", "--manifest-path", "uniffi-bindgen/Cargo.toml", "--",
        "generate", "--library", bindgenLib.absolutePath, "--language", "kotlin",
        "--out-dir", p2pBindings.get().asFile.absolutePath,
    )
    inputs.file(p2pBuiltLib)
    outputs.dir(p2pBindings)
    doFirst {
        p2pBindings.get().asFile.deleteRecursively()
        bindgenLib.parentFile.mkdirs()
        p2pBuiltLib.copyTo(bindgenLib, overwrite = true)
    }
    doLast {
        // The app's P2P code names these; if a new UniFFI or p2p-core renames one, fail here with the reason.
        val outDir = p2pBindings.get().asFile
        val kt = outDir.walkTopDown().firstOrNull { it.name == "p2p_core.kt" }
            ?: throw GradleException(
                "UniFFI wrote no p2p_core.kt into $outDir.\n" +
                    "Files it did write: " +
                    outDir.walkTopDown().filter { it.isFile }.map { it.relativeTo(outDir).path }.toList()
                        .ifEmpty { listOf("none") }.joinToString(", ") + ".\n" +
                    "Library read: ${bindgenLib.absolutePath} (exists: ${bindgenLib.isFile}).\n" +
                    "Library inspection (what UniFFI reads from):\n" +
                    "  file: " + commandOutput("file", bindgenLib.absolutePath) + "\n" +
                    "  UNIFFI_META symbols in the dynamic table: " +
                    commandOutput("sh", "-c", "nm -D \"\$0\" 2>&1 | grep -c UNIFFI_META; true", bindgenLib.absolutePath) + "\n" +
                    "  UNIFFI_META symbols in the full table: " +
                    commandOutput("sh", "-c", "nm \"\$0\" 2>&1 | grep -c UNIFFI_META; true", bindgenLib.absolutePath) + "\n" +
                    "UniFFI's output, last 40 lines:\n" +
                    bindgenOutput.toString(Charsets.UTF_8).lines().takeLast(40).joinToString("\n"),
            )
        // UniFFI may quote identifiers with backticks (`defaultEngineConfig`); the Kotlin is the same either way, so the
        // check reads the text without them. Without this, `fun defaultEngineConfig` never matches a quoted declaration.
        val text = kt.readText().replace("`", "")
        val needed = listOf(
            "class P2pEngine", "class P2pException", "fun defaultEngineConfig", "libraryOverride",
            "class MetadataTimeout", "class NoFile", "class Stopped",
        )
        val missing = needed.filter { it !in text }
        if (missing.isNotEmpty()) {
            throw GradleException(
                "The generated P2P bindings lack $missing. desktopMain/p2p (P2PLibrary.kt, P2PPlatformDesktop.kt) " +
                    "expects them: update those files to the new bindings.",
            )
        }
    }
}

// The desktop code compiles against the bindings, so they are generated (and the library built) first.
tasks.matching { it.name == "compileKotlinDesktop" }.configureEach { dependsOn(generateP2pBindings) }
