val pearBuildGenerated = layout.buildDirectory.dir("generated/pearbuild/kotlin")
val generatePearBuild by tasks.registering {
    inputs.property("pearVersion", pearVersionValue)
    inputs.property("updateRepo", updateRepoValue)
    outputs.dir(pearBuildGenerated)
    doLast {
        val dir = pearBuildGenerated.get().asFile.resolve("com/mediahub/pear/update")
        dir.mkdirs()
        dir.resolve("PearBuild.kt").writeText(
            """
            |package com.mediahub.pear.update
            |
            |// Written by shared/build.gradle.kts from gradle.properties. Do not edit.
            |object PearBuild {
            |    const val VERSION: String = "$pearVersionValue"
            |    const val UPDATE_REPO: String = "$updateRepoValue"
            |}
            |""".trimMargin(),
        )
    }
}

